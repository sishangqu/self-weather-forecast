provs = {x["code"]: x["name"] for x in json.load(urllib.request.urlopen(
    "https://raw.githubusercontent.com/modood/Administrative-divisions-of-China/master/dist/provinces.json"))}
cities = []
for c in json.load(urllib.request.urlopen(
        "https://raw.githubusercontent.com/modood/Administrative-divisions-of-China/master/dist/cities.json")):
    n = c["name"]
    if n == "市辖区" or not n.endswith("市"):
        continue
    pc = c["provinceCode"]
    if pc in ("11", "12", "31", "50") and n in ("北京市", "天津市", "上海市", "重庆市"):
        continue
    cities.append({"name": n, "province": provs.get(pc, pc)})
for m in ("北京市", "天津市", "上海市", "重庆市"):
    cities.append({"name": m, "province": m})
print("城市总数:", len(cities))


def norm_admin(s):
    if not s:
        return ""
    for suf in ("省", "市", "自治区", "壮族", "回族", "维吾尔", "特别行政区"):
        s = s.replace(suf, "")
    return s


def match_strict(city, res):
    target = norm_admin(city["province"])
    for x in res:
        if x.get("country") and "中国" in str(x.get("country")):
            if norm_admin(x.get("admin1", "")) == target:
                return x
    return None


S = requests.Session()
rows, used = [], {"api": 0, "hard": 0}
for i, city in enumerate(cities):
    name = city["name"]
    base = name[:-1] if name.endswith("市") else name
    found = None
    # 1) API：去市/带市/拼音 三种写法，严格省份匹配
    queries = [base, name, "".join(lazy_pinyin(base))]
    for q in queries:
        try:
            r = S.get("https://geocoding-api.open-meteo.com/v1/search",
                      params={"name": q, "count": 8, "language": "zh"}, timeout=15)
            res = r.json().get("results")
        except Exception:
            res = None
        if res:
            found = match_strict(city, res)
            if found:
                break
        time.sleep(0.1)
    if not found:
        found = HARDCODE.get(name) or MUNI.get(name)
        if found:
            used["hard"] += 1
            rows.append((city["province"], PROV_FILE.get(city["province"], ""),
                         name, base, found[0], found[1]))
            continue
        print("!! 仍未找到:", name)
        continue
    used["api"] += 1
    rows.append((city["province"], PROV_FILE.get(city["province"], ""),
                 name, base, round(found["latitude"], 4), round(found["longitude"], 4)))
    if (i + 1) % 50 == 0:
        print(f"  {i+1}/{len(cities)} 完成 api={used['api']} hard={used['hard']}")

with open("cities.csv", "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(["province", "province_file", "name", "file", "lat", "lon"])
    w.writerows(rows)

print("完成:", len(rows), "（api:", used["api"], "| hard:", used["hard"], "）")
